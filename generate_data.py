"""生成课堂演示用的学生成绩 Excel 表"""
import pandas as pd

# 15 名学生的模拟成绩数据
data = {
    "学号": [f"2024{i:03d}" for i in range(1, 16)],
    "姓名": [
        "张伟", "李娜", "王强", "刘洋", "陈静",
        "杨帆", "赵敏", "孙浩", "周婷", "吴磊",
        "郑爽", "冯军", "何丽", "郭鹏", "韩雪",
    ],
    "语文": [85, 92, 78, 88, 95, 67, 90, 82, 76, 89, 94, 71, 86, 80, 91],
    "数学": [90, 85, 95, 72, 88, 79, 93, 68, 84, 91, 77, 86, 90, 75, 83],
    "英语": [78, 88, 82, 91, 90, 85, 76, 89, 92, 74, 86, 80, 95, 87, 79],
}

df = pd.DataFrame(data)
df["总分"] = df["语文"] + df["数学"] + df["英语"]
df["平均分"] = (df["总分"] / 3).round(1)

df.to_excel("students.xlsx", index=False)
print("已生成 students.xlsx，共", len(df), "条记录")
